// `content/` нь Vercel-ийн deploy-д ордоггүй (.vercelignore) тул нийтлэгдсэн хуудаснаас build үед JS модуль үүсгэнэ.
//
// Эзэмшигчийн шийдвэр (2026-11-26): ЗӨВХӨН товч тайлбар (summary), хугацаа/мэдээ алдуулалт/давтамж/эдгэрэлт (facts),
// «юу вэ» (what), «явц» (procedure). Эсрэг заалт, гаж нөлөө, арчилгаа, үнэ, FAQ ОРОХГҮЙ — тэр асуултыг үргэлж эмч, ажилтан
// хариулна (policy.js). Үнэ нь каталогоос (settings/catalog) л.
import { plain } from './render.mjs';
import { FACT_ROWS } from './pages.mjs';

export const PAGE_TEXT_MAX = 900;
export const PAGES_KNOWLEDGE_FILE = 'api/_lib/generated/pages-knowledge.js';
export const PAGE_KNOWLEDGE_SECTIONS = Object.freeze(['what', 'procedure']);

const flat = (v) => plain(v).replace(/\s+/g, ' ').trim();

/** Нэг хуудас → { slug, name, catalogIds, text } (markup-гүй, ≤ PAGE_TEXT_MAX) */
export function pageKnowledge(page) {
  const facts = FACT_ROWS.map(([k, label]) => (page.facts && page.facts[k] ? `${label}: ${flat(page.facts[k])}` : '')).filter(Boolean).join('; ');
  const parts = [flat(page.summary), facts, ...PAGE_KNOWLEDGE_SECTIONS.map((k) => flat(page.sections && page.sections[k]))].filter(Boolean);
  return {
    slug: page.slug,
    name: flat(page.name || page.h1),
    catalogIds: [...(page.catalogIds || [])],
    text: parts.join(' · ').slice(0, PAGE_TEXT_MAX),
  };
}

/** Нийтлэгдсэн хуудсууд → api/_lib/generated/pages-knowledge.js-ийн агуулга (slug-аар эрэмбэлсэн — тогтвортой) */
export function pagesKnowledgeModule(pages) {
  const rows = [...pages].sort((a, b) => a.slug.localeCompare(b.slug)).map(pageKnowledge);
  return '/* generated by tools/build.mjs (эх: content/pages — нийтлэгдсэн хуудас; tools/lib/messenger-pages.mjs) — гараар бүү засаарай */\n'
    + `export const PAGES = Object.freeze(${JSON.stringify(rows, null, 1).replace(/</g, '\\u003c')});\n`;
}
