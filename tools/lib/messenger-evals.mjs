// Messenger AI-ийн eval кейс (tools/evals/messenger.jsonl) → api/_lib/generated/eval-cases.js (tools/build.mjs).
// `tools/` нь Vercel-ийн deploy-д ордоггүй (.vercelignore) тул admin-ийн «Eval» (api/admin.js) ажиллуулахад JS модуль болгоно.
// Зөвхөн бодит Claude-тэй eval-д хэрэгтэй талбар: id, turns, expect, tags (gold/bad/trap — offline тестэд л).
export const EVAL_CASES_FILE = 'api/_lib/generated/eval-cases.js';

/** @param {string} jsonl */
export function evalCasesModule(jsonl) {
  const rows = String(jsonl).trim().split('\n').filter(Boolean).map((l, i) => {
    let c;
    try { c = JSON.parse(l); } catch (e) { throw new Error(`tools/evals/messenger.jsonl:${i + 1}: JSON буруу — ${e.message}`); }
    return { id: c.id, turns: c.turns.map((t) => ({ role: t.role, text: t.text })), expect: c.expect, tags: c.tags || [] };
  });
  return '/* generated by tools/build.mjs (эх: tools/evals/messenger.jsonl; tools/lib/messenger-evals.mjs) — гараар бүү засаарай */\n'
    + `export const EVAL_CASES = Object.freeze(${JSON.stringify(rows, null, 1).replace(/</g, '\\u003c')});\n`;
}
