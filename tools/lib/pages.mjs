import { siteHeader, siteFooter } from './layout.mjs';
import { esc, inline, blocks, plain, mnDate } from './render.mjs';
import { priceInfo } from './content.mjs';

export const GENERATED = '<!-- generated by tools/build.mjs — гараар бүү засаарай (эх: content/) -->';

const FONTS = 'https://fonts.googleapis.com/css2?family=Manrope:wght@500;600;700;800&family=Montserrat:wght@600;700;800&display=swap';

const SECTION_META = [
  ['what', 'tuhai', (p) => (p.headings && p.headings.what) || `${p.name} гэж юу вэ`],
  ['suits', 'hend-tohiroh', (p) => (p.headings && p.headings.suits) || 'Хэнд тохирох вэ'],
  ['contraindications', 'esreg-zaalt', (p) => (p.headings && p.headings.contraindications) || 'Хэнд хийхгүй вэ (эсрэг заалт)'],
  ['procedure', 'yavts', (p) => (p.headings && p.headings.procedure) || 'Эмчилгээ хэрхэн явагддаг вэ'],
  ['aftercare', 'archilgaa', (p) => (p.headings && p.headings.aftercare) || 'Эмчилгээний дараах арчилгаа'],
  ['sideEffects', 'gaj-noloo', (p) => (p.headings && p.headings.sideEffects) || 'Гаж нөлөө, эрсдэл'],
  ['price', 'une', (p) => (p.headings && p.headings.price) || 'Үнэ'],
];

const FACT_ROWS = [['duration', 'Үргэлжлэх хугацаа'], ['anesthesia', 'Мэдээ алдуулалт'], ['sessions', 'Давтамж, тоо'], ['downtime', 'Эдгэрэлт']];

const ind = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

/** <head> (дэд хуудас) */
function head({ site, title, description, canonical, robots, ldJson, preview }) {
  return [
    '<!DOCTYPE html>',
    GENERATED,
    '<html lang="mn">',
    '<head>',
    '  <meta charset="UTF-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1">',
    `  <title>${esc(preview ? '[НООРОГ] ' + title : title)}</title>`,
    `  <meta name="description" content="${esc(description)}">`,
    '  <meta name="theme-color" content="#654186">',
    `  <link rel="canonical" href="${esc(canonical)}">`,
    ...(robots ? [`  <meta name="robots" content="${robots}">`] : []),
    '',
    '  <meta property="og:type" content="article">',
    `  <meta property="og:site_name" content="${esc(site.name)}">`,
    `  <meta property="og:title" content="${esc(title)}">`,
    `  <meta property="og:description" content="${esc(description)}">`,
    `  <meta property="og:url" content="${esc(canonical)}">`,
    '  <meta property="og:locale" content="mn_MN">',
    `  <meta property="og:image" content="${site.origin}/assets/img/og-image.jpg">`,
    '  <meta property="og:image:width" content="1200">',
    '  <meta property="og:image:height" content="630">',
    '  <meta name="twitter:card" content="summary_large_image">',
    '',
    '  <link rel="preconnect" href="https://fonts.googleapis.com">',
    '  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    `  <link href="${FONTS.replace(/&/g, '&amp;')}" rel="stylesheet" media="print" onload="this.media='all'">`,
    `  <noscript><link href="${FONTS.replace(/&/g, '&amp;')}" rel="stylesheet"></noscript>`,
    '',
    '  <link rel="stylesheet" href="/assets/css/style.css">',
    '  <link rel="icon" href="/favicon.ico" sizes="any">',
    '  <link rel="icon" type="image/png" sizes="48x48" href="/assets/img/favicon-48.png">',
    '  <link rel="apple-touch-icon" sizes="180x180" href="/assets/img/apple-touch-icon.png">',
    ...(ldJson ? ['', '  <script type="application/ld+json">', '  ' + ldJson, '  </script>'] : []),
    ...(preview ? ['  <style>mark.dr-q{background:#ffe08a;color:#3a2a00;padding:0 3px;border-radius:4px}.draft-banner{position:fixed;left:0;right:0;bottom:0;z-index:9999;background:#7a1f2b;color:#fff;font:14px/1.45 system-ui,sans-serif;padding:10px 16px;max-height:45vh;overflow:auto}.draft-banner summary{cursor:pointer}.draft-banner li{margin:2px 0}</style>'] : []),
    '</head>',
  ].join('\n');
}

function previewBanner(info) {
  const issues = info.issues || [];
  return [
    '<div class="draft-banner" role="note">',
    `  <strong>НООРОГ — эмчийн хяналтад ороогүй, нийтлэгдээгүй.</strong> Хувилбар: <code>${esc(info.hash)}</code> · Үг: ${info.words} · Эмчид асуух: ${info.markers} · Асуудал: ${issues.length}`,
    ...(issues.length ? ['  <details><summary>Асуудлууд</summary><ul>', ...issues.map((m) => `    <li>${esc(m)}</li>`), '  </ul></details>'] : []),
    '</div>',
  ].join('\n');
}

function crumbsHtml(items) {
  return [
    '<nav class="crumbs" aria-label="Breadcrumb">',
    '  <ol>',
    ...items.map((it, i) => (i === items.length - 1
      ? `    <li><span aria-current="page">${esc(it.name)}</span></li>`
      : `    <li><a href="${esc(it.path)}">${esc(it.name)}</a></li>`)),
    '  </ol>',
    '</nav>',
  ].join('\n');
}

function ctaHtml(site, book, title, text) {
  return [
    '<section class="section--tight">',
    '  <div class="container">',
    '    <div class="cta">',
    '      <div>',
    `        <h2>${esc(title)}</h2>`,
    `        <p>${esc(text)}</p>`,
    '        <div class="cta__pay"><span class="pay">Storepay</span><span class="pay">Pocket</span><span class="pay">Хуваан төлөх боломжтой</span></div>',
    '      </div>',
    '      <div class="cta__actions">',
    `        <a class="cta__phone" href="tel:${site.phone.tel}" data-site="tel phone">${site.phone.display}</a>`,
    `        <a class="btn btn--gold btn--lg" href="${esc(book)}">Цаг захиалах</a>`,
    '      </div>',
    '    </div>',
    '  </div>',
    '</section>',
  ].join('\n');
}

function faqHtml(faq, c, slug) {
  return [
    '<div class="faq">',
    ...faq.map((f, i) => {
      const id = `faq-${slug}-${i + 1}`;
      return [
        '  <div class="faq__item">',
        `    <button class="faq__q" type="button" aria-expanded="false" aria-controls="${id}">${inline(f.q, c)}<span class="plus"><svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round"><path d="M12 5v14M5 12h14"/></svg></span></button>`,
        `    <div class="faq__a" id="${id}"><div>${blocks(f.a, c)}</div></div>`,
        '  </div>',
      ].join('\n');
    }),
    '</div>',
  ].join('\n');
}

/**
 * @param page   контентын объект
 * @param ctx    { site, catalog, R, pageUrl, hubLive, preview, reviewer: {key, doc}|null, ldJson, info }
 */
export function renderTreatment(page, ctx) {
  const { site, catalog } = ctx;
  const url = site.origin + '/emchilgee/' + page.slug;
  const c = { preview: ctx.preview, where: page.slug, linkOk: ctx.linkOk };
  const items = (page.catalogIds || []).map((id) => catalog.treatments.find((t) => t.id === id)).filter(Boolean);
  const price = priceInfo(items);
  const book = `/?svc=${page.slug}#contact`;
  const layoutCtx = { home: false, site, book, pageUrl: ctx.pageUrl, hubLive: ctx.hubLive, current: page.slug };
  const crumbs = [{ name: 'Нүүр', path: '/' }, { name: 'Эмчилгээ', path: '/emchilgee' }, { name: page.name, path: '/emchilgee/' + page.slug }];
  const rev = ctx.reviewer;

  const facts = [
    ...FACT_ROWS.map(([k, label]) => `<tr><th scope="row">${label}</th><td>${inline(page.facts[k], c)}</td></tr>`),
    `<tr><th scope="row">Үнэ</th><td>${esc(price.text)}</td></tr>`,
  ];
  const related = (page.related || []).map((s) => ({ s, url: ctx.pageUrl(s), p: ctx.relatedPages.find((x) => x.slug === s) })).filter((x) => x.url && x.p);
  const toc = [...SECTION_META.map(([, id, h]) => [id, h(page)]), ...(related.length ? [['holbootoi', 'Холбоотой эмчилгээ']] : []), ['asuult', 'Түгээмэл асуулт'], ['eh-survalj', 'Эх сурвалж']];

  const priceTable = items.length ? [
    '<table class="facts">',
    '  <caption class="sr-only">Үйлчилгээ, үнэ</caption>',
    '  <thead><tr><th scope="col">Үйлчилгээ</th><th scope="col">Үнэ</th></tr></thead>',
    '  <tbody>',
    ...items.map((t) => `    <tr><th scope="row">${esc(t.n)}${t.t ? ` <span class="meta">· ${esc(t.t)}</span>` : ''}</th><td>${esc(t.p || 'Үзлэгийн дараа тодорхойлно')}</td></tr>`),
    '  </tbody>',
    '</table>',
  ].join('\n') : '';

  const sections = SECTION_META.map(([key, id, h]) => [
    `<section id="${id}" aria-labelledby="h-${id}">`,
    `  <h2 id="h-${id}">${esc(h(page))}</h2>`,
    ind(blocks(page.sections[key], { ...c, where: `${page.slug} ${key}` }), 2),
    ...(key === 'price' && priceTable ? [ind(priceTable, 2)] : []),
    '</section>',
  ].join('\n'));

  const body = [
    '<body>',
    ind(siteHeader(layoutCtx), 2),
    '',
    '  <main class="page" id="main">',
    '    <div class="page-head">',
    '      <div class="container container--narrow">',
    ind(crumbsHtml(crumbs), 8),
    `        <h1>${inline(page.h1, c)}</h1>`,
    `        <p class="lead">${inline(page.summary, c)}</p>`,
    '        <p class="byline">' + (rev
      ? `<span>Хянасан: <strong>${esc(rev.doc.name)}${rev.doc.jobTitle ? ', ' + esc(rev.doc.jobTitle) : ''}</strong></span><span>Шинэчилсэн: <time datetime="${esc(page.lastReviewed)}">${esc(mnDate(page.lastReviewed))}</time></span>`
      : '<span>Эмчийн хяналтад хүлээгдэж буй ноорог</span>') + '</p>',
    '      </div>',
    '    </div>',
    '',
    '    <div class="container container--narrow prose">',
    '      <table class="facts">',
    '        <caption class="sr-only">Товч мэдээлэл</caption>',
    '        <tbody>',
    ...facts.map((r) => '          ' + r),
    '        </tbody>',
    '      </table>',
    '',
    '      <nav class="toc" aria-labelledby="toc-h">',
    '        <h2 id="toc-h">Агуулга</h2>',
    '        <ol>',
    ...toc.map(([id, h]) => `          <li><a href="#${id}">${esc(h)}</a></li>`),
    '        </ol>',
    '      </nav>',
    '',
    ...sections.map((s) => ind(s, 6) + '\n'),
    ...(related.length ? [ind([
      '<section id="holbootoi" aria-labelledby="h-holbootoi">',
      '  <h2 id="h-holbootoi">Холбоотой эмчилгээ</h2>',
      '  <div class="hub-cards">',
      ...related.map((r) => `    <a class="hub-card" href="${esc(r.url)}"><h3>${esc(r.p.name)}</h3><p>${esc(plain(r.p.summary))}</p></a>`),
      '  </div>',
      '</section>',
    ].join('\n'), 6) + '\n'] : []),
    ind([
      '<section id="asuult" aria-labelledby="h-asuult">',
      '  <h2 id="h-asuult">Түгээмэл асуулт</h2>',
      ind(faqHtml(page.faq, c, page.slug), 2),
      '</section>',
    ].join('\n'), 6),
    '',
    ind([
      '<section id="eh-survalj" aria-labelledby="h-eh-survalj">',
      '  <h2 id="h-eh-survalj">Эх сурвалж</h2>',
      '  <ol class="sources">',
      ...page.sources.map((s) => `    <li><a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.title)}</a>. ${esc(s.publisher)}${s.year ? ', ' + esc(s.year) : ''}.${s.accessed ? ` Үзсэн: ${esc(s.accessed)}.` : ''}</li>`),
      '  </ol>',
      `  <p class="disclaimer">${esc(site.medicalDisclaimer)}</p>`,
      '</section>',
    ].join('\n'), 6),
    '    </div>',
    '',
    ind(ctaHtml(site, book, page.ctaTitle || 'Эмчийн үзлэгт цаг захиалах', 'Эмчилгээ танд тохирох эсэх, хэдэн удаа шаардлагатайг эмч үзлэгээр тогтооно.'), 4),
    '  </main>',
    '',
    ind(siteFooter(layoutCtx), 2),
    ...(ctx.preview ? [ind(previewBanner(ctx.info), 2)] : []),
    '',
    '  <script src="/assets/js/main.js"></script>',
    '</body>',
    '</html>',
    '',
  ].join('\n');

  return head({ site, title: page.title, description: page.description, canonical: url, robots: ctx.preview ? 'noindex, nofollow' : null, ldJson: ctx.ldJson, preview: ctx.preview }) + '\n' + body;
}

/**
 * Hub: ангилал бүрээр нийтлэгдсэн хуудасны карт + catalog-ийн бүх мөр.
 * @param ctx { site, catalog, R, pageUrl, hubLive:true, preview, pages (харагдах), byId, ldJson }
 */
export function renderHub(hub, ctx) {
  const { site, catalog, R } = ctx;
  const url = site.origin + '/emchilgee';
  const c = { preview: ctx.preview, where: 'hub', linkOk: ctx.linkOk };
  const layoutCtx = { home: false, site, pageUrl: ctx.pageUrl, hubLive: true, current: 'hub' };
  const crumbs = [{ name: 'Нүүр', path: '/' }, { name: 'Эмчилгээ', path: '/emchilgee' }];
  const groups = Object.entries(catalog.cats).map(([key, label]) => {
    const rows = catalog.treatments.filter((t) => t.c === key);
    if (!rows.length) return '';
    const cards = ctx.pages.filter((p) => p.category === key);
    return [
      `<section id="${key}" aria-labelledby="h-${key}">`,
      `  <h2 id="h-${key}">${esc(label)}</h2>`,
      ...(hub.intros && hub.intros[key] ? [ind(blocks(hub.intros[key], { ...c, where: `hub ${key}` }), 2)] : []),
      ...(cards.length ? [
        '  <div class="hub-cards">',
        ...cards.map((p) => `    <a class="hub-card" href="/emchilgee/${p.slug}"><h3>${esc(p.name)}</h3><p>${esc(plain(p.summary))}</p></a>`),
        '  </div>',
      ] : []),
      '  <div class="list">',
      ...rows.map((t) => '    ' + R.row(t, catalog.cats, { pages: ctx.byId, book: '/#contact' })),
      '  </div>',
      '</section>',
    ].join('\n');
  }).filter(Boolean);

  const body = [
    '<body>',
    ind(siteHeader(layoutCtx), 2),
    '',
    '  <main class="page" id="main">',
    '    <div class="page-head">',
    '      <div class="container container--narrow">',
    ind(crumbsHtml(crumbs), 8),
    `        <h1>${inline(hub.h1, c)}</h1>`,
    ...hub.intro.map((p) => `        <p class="lead">${inline(p, c)}</p>`),
    '      </div>',
    '    </div>',
    '',
    '    <div class="container container--narrow prose">',
    '      <nav class="toc" aria-labelledby="toc-h">',
    '        <h2 id="toc-h">Ангилал</h2>',
    '        <ol>',
    ...Object.entries(catalog.cats).filter(([k]) => catalog.treatments.some((t) => t.c === k)).map(([k, l]) => `          <li><a href="#${k}">${esc(l)}</a></li>`),
    '        </ol>',
    '      </nav>',
    '',
    ...groups.map((g) => ind(g, 6) + '\n'),
    `      <p class="disclaimer">${esc(site.medicalDisclaimer)}</p>`,
    '    </div>',
    '',
    ind(ctaHtml(site, '/#contact', 'Аль эмчилгээ танд тохирох вэ?', 'Эмч эхлээд арьсыг тань үзэж, тохирох эмчилгээ, давтамжийг тодорхойлно.'), 4),
    '  </main>',
    '',
    ind(siteFooter(layoutCtx), 2),
    ...(ctx.preview ? [ind(previewBanner(ctx.info), 2)] : []),
    '',
    '  <script src="/assets/js/main.js"></script>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
  return head({ site, title: hub.title, description: hub.description, canonical: url, robots: ctx.preview ? 'noindex, nofollow' : null, ldJson: ctx.ldJson, preview: ctx.preview }) + '\n' + body;
}
